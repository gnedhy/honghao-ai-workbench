-- Revision links change read grouping only; frozen cost records remain immutable.
CREATE TABLE research_event_revisions (
 event_id TEXT PRIMARY KEY REFERENCES research_events(id),
 root_event_id TEXT NOT NULL REFERENCES research_events(id),
 actor TEXT NOT NULL, recorded_at TEXT NOT NULL,
 CHECK(event_id<>root_event_id),
 _order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE INDEX research_event_revisions_root ON research_event_revisions(root_event_id);
CREATE OR REPLACE FUNCTION research_refresh_history(target TEXT) RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE item RECORD; value JSONB; previous JSONB; basis JSONB; current_price NUMERIC; old_price NUMERIC; movement JSONB; period JSONB; event_inputs JSONB; snapshot JSONB; candidate RECORD; counter BIGINT:=0;
BEGIN
 PERFORM pg_advisory_xact_lock(hashtextextended(target,83124));
 INSERT INTO research_history_versions(product_id,revision) VALUES(target,1) ON CONFLICT(product_id) DO UPDATE SET revision=research_history_versions.revision+1;
 DELETE FROM research_history_reads h WHERE product_id=target
 AND NOT EXISTS(SELECT 1 FROM research_cost_records c WHERE c.product_id=target AND c.event_id=h.event_id)
 AND NOT EXISTS(SELECT 1 FROM research_backfill_records b WHERE b.product_id=target AND COALESCE(b.summary_payload::jsonb->>'event_id','backfill:'||b.purchase_version)=h.event_id);
 DELETE FROM research_history_reads h WHERE product_id=target AND EXISTS(SELECT 1 FROM research_event_revisions r WHERE r.event_id=h.event_id);
 FOR item IN
   SELECT COALESCE(h.payload,b.summary_payload::jsonb) AS value,
     COALESCE(h.line_prices,research_line_prices(b.payload::jsonb)) AS prices,
     COALESCE(h.payload->'_visibility',research_visibility(b.payload::jsonb)) AS visibility,
     h.event_id IS NULL AS changed,0 AS category,b.purchase_version AS ordering
   FROM research_backfill_records b LEFT JOIN research_history_reads h ON h.product_id=b.product_id AND h.event_id=COALESCE(b.summary_payload::jsonb->>'event_id','backfill:'||b.purchase_version) WHERE b.product_id=target
   UNION ALL
   SELECT COALESCE(h.payload,c.current_payload::jsonb || jsonb_build_object('record_type','formal','product_id',c.product_id,'effective_date',substring(c.current_payload::jsonb->>'recorded_at',1,10))) ||
     CASE WHEN audit.items IS NULL THEN '{}'::jsonb ELSE jsonb_build_object(
       'event_id',e.id,'source_event_id',c.event_id,'revision_events',audit.items,
       'effective_date',e.read_period->>'price_date','purchase_version',e.read_period->'version',
       'recorded_at',e.recorded_at,'reason',e.reason || ' · 已修订') END,
     COALESCE(h.line_prices,research_line_prices(c.payload::jsonb)),
     COALESCE(h.payload->'_visibility',research_visibility(c.payload::jsonb)),
     h.event_id IS NULL,1,c.sequence
   FROM (
     SELECT DISTINCT ON(COALESCE(r.root_event_id,c.event_id)) c.*,
       COALESCE(r.root_event_id,c.event_id) AS canonical_id
     FROM research_cost_records c LEFT JOIN research_event_revisions r ON r.event_id=c.event_id
     WHERE c.product_id=target ORDER BY COALESCE(r.root_event_id,c.event_id),c.sequence DESC
   ) c JOIN research_events e ON e.id=c.canonical_id
   LEFT JOIN research_history_reads h ON h.product_id=c.product_id AND h.event_id=c.event_id
     AND NOT EXISTS(SELECT 1 FROM research_event_revisions r WHERE r.root_event_id=c.canonical_id)
   LEFT JOIN LATERAL (
     SELECT jsonb_agg(jsonb_build_object('event_id',a.event_id,'recorded_at',a.current_payload::jsonb->>'recorded_at',
       'reason',a.current_payload::jsonb->>'reason','latest_cost',a.current_payload::jsonb->'latest_cost',
       'inventory_cost',a.current_payload::jsonb->'inventory_cost') ORDER BY a.sequence) AS items
     FROM research_cost_records a WHERE a.product_id=target AND
       (a.event_id=e.id OR a.event_id IN(SELECT event_id FROM research_event_revisions WHERE root_event_id=e.id))
       AND EXISTS(SELECT 1 FROM research_event_revisions WHERE root_event_id=e.id)
   ) audit ON true
   ORDER BY category,ordering
 LOOP
   value:=item.value;
   IF item.changed AND value->>'record_type'='formal' THEN
     SELECT jsonb_build_object('purchase_period',read_period,'prices',read_prices) INTO event_inputs FROM research_events WHERE id=value->>'event_id' AND reason='采购正式价格更新';
     period:=event_inputs->'purchase_period';
     IF NULLIF(period->>'price_date','') IS NULL AND event_inputs IS NOT NULL THEN
       SELECT id,version,price_date INTO candidate FROM procurement_price_batches WHERE published_at::timestamptz<=(value->>'recorded_at')::timestamptz ORDER BY version DESC LIMIT 1;
       IF candidate.id IS NOT NULL THEN
         SELECT jsonb_object_agg(code,latest_price) INTO snapshot FROM procurement_price_batch_items WHERE batch_id=candidate.id;
         IF snapshot IS NOT NULL AND event_inputs->'prices' IS NOT NULL AND event_inputs->'prices' NOT IN ('{}'::jsonb,'null'::jsonb) AND NOT EXISTS(
           SELECT 1 FROM jsonb_each(event_inputs->'prices') price WHERE (price.value->>'latest_price')::numeric IS DISTINCT FROM (snapshot->>price.key)::numeric
         ) THEN period:=jsonb_build_object('id',candidate.id,'version',candidate.version,'price_date',candidate.price_date); END IF;
       END IF;
     END IF;
     IF NULLIF(period->>'price_date','') IS NOT NULL THEN value:=value || jsonb_build_object('effective_date',period->>'price_date','purchase_version',period->'version'); END IF;
   END IF;
   current_price:=round((value->>'latest_cost')::numeric,2);
   IF previous IS NOT NULL AND (value ? 'revision_events' OR basis IS NULL OR basis->>'latest_cost' IS NULL OR current_price IS NULL OR current_price IS DISTINCT FROM round((previous->>'latest_cost')::numeric,2)) THEN basis:=previous; END IF;
   old_price:=round((basis->>'latest_cost')::numeric,2);
   IF basis IS NULL THEN movement:=jsonb_build_object('percent',NULL,'reason','首次正式记录，暂无上期成本');
   ELSIF current_price IS NULL OR old_price IS NULL THEN movement:=jsonb_build_object('percent',NULL,'reason','本期或上期缺少价格，暂无对比');
   ELSIF old_price=0 THEN movement:=jsonb_build_object('percent',NULL,'reason','上期成本为零，无法计算百分比');
   ELSE movement:=jsonb_build_object('percent',(current_price-old_price)/old_price*100,'reason','行情优先成本（按两位小数比较）：' || old_price::text || ' → ' || current_price::text); END IF;
   counter:=counter+1;
   INSERT INTO research_history_reads(product_id,event_id,record_type,effective_date,recorded_at,purchase_version,ordinal,payload,line_prices) VALUES(target,COALESCE(value->>'event_id','backfill:'||item.ordering),COALESCE(value->>'record_type','backfill'),COALESCE(value->>'effective_date',''),COALESCE(value->>'recorded_at',''),(value->>'purchase_version')::bigint,counter,
     (value-ARRAY['graph','calculations','formula','source_hashes','latest','inventory','lines']) || jsonb_build_object('_visibility',item.visibility,'change',movement,'comparison_basis',CASE WHEN basis IS NULL THEN NULL ELSE jsonb_build_object('record_type',basis->'record_type','purchase_version',basis->'purchase_version','effective_date',basis->'effective_date','event_id',basis->'event_id','latest_cost',basis->'latest_cost') END),item.prices)
   ON CONFLICT(product_id,event_id) DO UPDATE SET record_type=EXCLUDED.record_type,effective_date=EXCLUDED.effective_date,
    recorded_at=EXCLUDED.recorded_at,purchase_version=EXCLUDED.purchase_version,ordinal=EXCLUDED.ordinal,payload=EXCLUDED.payload,line_prices=EXCLUDED.line_prices
   WHERE (research_history_reads.record_type,research_history_reads.effective_date,research_history_reads.recorded_at,research_history_reads.purchase_version,research_history_reads.ordinal,research_history_reads.payload,research_history_reads.line_prices)
    IS DISTINCT FROM (EXCLUDED.record_type,EXCLUDED.effective_date,EXCLUDED.recorded_at,EXCLUDED.purchase_version,EXCLUDED.ordinal,EXCLUDED.payload,EXCLUDED.line_prices);
   previous:=value;
 END LOOP;
END $$;



CREATE TABLE procurement_batch_revisions (
 batch_id TEXT PRIMARY KEY REFERENCES procurement_price_batches(id),
 note TEXT NOT NULL, actor TEXT NOT NULL, recorded_at TEXT NOT NULL,
 _order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
INSERT INTO honghao_meta.read_versions(table_name) VALUES ('research_event_revisions'),('procurement_batch_revisions');
CREATE TRIGGER read_version AFTER INSERT OR UPDATE OR DELETE OR TRUNCATE ON research_event_revisions FOR EACH STATEMENT EXECUTE FUNCTION honghao_meta.bump_read_version();
CREATE TRIGGER read_version AFTER INSERT OR UPDATE OR DELETE OR TRUNCATE ON procurement_batch_revisions FOR EACH STATEMENT EXECUTE FUNCTION honghao_meta.bump_read_version();
