CREATE TABLE sales_activity (
 batch_id TEXT NOT NULL REFERENCES sales_batches(id), product_id TEXT NOT NULL,
 trials BIGINT NOT NULL DEFAULT 0 CHECK(trials>=0), adopted BIGINT NOT NULL DEFAULT 0 CHECK(adopted>=0),
 _order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE, PRIMARY KEY(batch_id,product_id)
);
INSERT INTO sales_activity(batch_id,product_id,trials,adopted)
 SELECT batch_id,product_id,sum(trials),sum(adopted) FROM (
 SELECT t.batch_id,i#>>'{}' AS product_id,count(*) AS trials,0 AS adopted FROM sales_trials t CROSS JOIN LATERAL jsonb_array_elements(t.product_ids) i GROUP BY t.batch_id,i#>>'{}'
 UNION ALL SELECT batch_id,product_id,0,count(*) FROM sales_records GROUP BY batch_id,product_id
 ) counts GROUP BY batch_id,product_id;
CREATE FUNCTION sales_update_activity() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE key TEXT;
BEGIN
 IF TG_OP='UPDATE' AND TG_TABLE_NAME='sales_records' THEN
   IF OLD.batch_id=NEW.batch_id AND OLD.product_id=NEW.product_id THEN RETURN NULL; END IF;
 END IF;
 IF TG_OP!='INSERT' THEN
   IF TG_TABLE_NAME='sales_trials' THEN
     FOR key IN SELECT DISTINCT x#>>'{}' FROM jsonb_array_elements(OLD.product_ids) x LOOP
       UPDATE sales_activity SET trials=trials-1 WHERE batch_id=OLD.batch_id AND product_id=key;
     END LOOP;
   ELSE UPDATE sales_activity SET adopted=adopted-1 WHERE batch_id=OLD.batch_id AND product_id=OLD.product_id; END IF;
 END IF;
 IF TG_OP!='DELETE' THEN
   IF TG_TABLE_NAME='sales_trials' THEN
     FOR key IN SELECT DISTINCT x#>>'{}' FROM jsonb_array_elements(NEW.product_ids) x LOOP
       INSERT INTO sales_activity(batch_id,product_id,trials) VALUES(NEW.batch_id,key,1) ON CONFLICT(batch_id,product_id) DO UPDATE SET trials=sales_activity.trials+1;
     END LOOP;
   ELSE INSERT INTO sales_activity(batch_id,product_id,adopted) VALUES(NEW.batch_id,NEW.product_id,1) ON CONFLICT(batch_id,product_id) DO UPDATE SET adopted=sales_activity.adopted+1; END IF;
 END IF;
 DELETE FROM sales_activity WHERE batch_id=CASE WHEN TG_OP='DELETE' THEN OLD.batch_id ELSE NEW.batch_id END AND trials=0 AND adopted=0;
 RETURN NULL;
END $$;
CREATE TRIGGER sales_activity_write AFTER INSERT OR UPDATE OR DELETE ON sales_trials FOR EACH ROW EXECUTE FUNCTION sales_update_activity();
