CREATE TABLE personalizations (
 _order bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 owner_id text PRIMARY KEY REFERENCES identity_users(id) ON DELETE CASCADE,
 revision integer NOT NULL DEFAULT 1 CHECK(revision>0),
 memory_enabled boolean NOT NULL DEFAULT true,
 instructions_path text,
 instructions_sha256 text,
 CHECK((instructions_path IS NULL)=(instructions_sha256 IS NULL)),
 memory_epoch bigint NOT NULL DEFAULT 1,
 memory_since text NOT NULL DEFAULT (now()::text),
 updated_at text NOT NULL DEFAULT (now()::text)
);
INSERT INTO personalizations(owner_id) SELECT id FROM identity_users;
CREATE TABLE project_instructions (
 _order bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 project_id text PRIMARY KEY REFERENCES projects(id) ON DELETE CASCADE,
 revision integer NOT NULL DEFAULT 1 CHECK(revision>0),
 content_path text,
 content_sha256 text,
 CHECK((content_path IS NULL)=(content_sha256 IS NULL)),
 updated_at text NOT NULL DEFAULT (now()::text)
);
CREATE TABLE personal_memories (
 _order bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 id text PRIMARY KEY,
 owner_id text NOT NULL REFERENCES identity_users(id) ON DELETE CASCADE,
 content text NOT NULL CHECK(length(trim(content))>0 AND length(content)<=1000),
 content_hash text NOT NULL,
 revision integer NOT NULL DEFAULT 1 CHECK(revision>0),
 manual boolean NOT NULL DEFAULT false,
 source_conversation_id text REFERENCES conversations(id) ON DELETE SET NULL,
 updated_at text NOT NULL DEFAULT (now()::text),
 UNIQUE(owner_id,content_hash)
);
CREATE INDEX personal_memories_owner ON personal_memories(owner_id,updated_at);
CREATE TABLE memory_suppressions (
 _order bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 owner_id text NOT NULL REFERENCES identity_users(id) ON DELETE CASCADE,
 content_hash text NOT NULL,
 PRIMARY KEY(owner_id,content_hash)
);
ALTER TABLE task_runs ADD COLUMN personalization_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb;
CREATE TABLE memory_extractions (
 _order bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 run_id text PRIMARY KEY REFERENCES task_runs(id) ON DELETE CASCADE,
 owner_id text NOT NULL REFERENCES identity_users(id) ON DELETE CASCADE,
 memory_epoch bigint NOT NULL,
 status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','running','completed','failed','discarded')),
 model_tokens bigint NOT NULL DEFAULT 0 CHECK(model_tokens>=0),
 created_at text NOT NULL DEFAULT (now()::text)
);
CREATE INDEX memory_extractions_pending ON memory_extractions(created_at) WHERE status='pending';
