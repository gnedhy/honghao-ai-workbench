-- Billing records intentionally survive conversation, run, and account removal.
CREATE TABLE ai_request_usage (
 _order bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 id text PRIMARY KEY,
 owner_id text NOT NULL,
 display_name text NOT NULL,
 department text NOT NULL,
 run_id text,
 model text NOT NULL,
 price_revision integer CHECK(price_revision>0),
 purpose text NOT NULL CHECK(purpose IN ('foreground','compaction','title','memory','test')),
 prices jsonb NOT NULL,
 status text NOT NULL DEFAULT 'inflight' CHECK(status IN ('inflight','completed','pending','void')),
 input_upper bigint NOT NULL CHECK(input_upper>=0),
 output_upper bigint NOT NULL CHECK(output_upper>=0),
 input_tokens bigint CHECK(input_tokens>=0),
 cached_tokens bigint CHECK(cached_tokens>=0 AND cached_tokens<=input_tokens),
 output_tokens bigint CHECK(output_tokens>=0),
 reported_total_tokens bigint CHECK(reported_total_tokens>=0),
 cost_cny numeric(24,12) NOT NULL CHECK(cost_cny>=0),
 created_at timestamptz NOT NULL DEFAULT now(),
 settled_at timestamptz,
 CHECK(status!='completed' OR (input_tokens IS NOT NULL AND cached_tokens IS NOT NULL AND output_tokens IS NOT NULL))
);
CREATE INDEX ai_request_usage_month ON ai_request_usage(created_at,owner_id) WHERE status!='void';
