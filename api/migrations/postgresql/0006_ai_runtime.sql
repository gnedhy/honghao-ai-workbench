CREATE TABLE ai_contexts (
    id text PRIMARY KEY,
    owner_id text NOT NULL REFERENCES identity_users(id),
    conversation_id text NOT NULL,
    task_id text,
    fingerprint text NOT NULL,
    thread_id text,
    reusable integer NOT NULL DEFAULT 1 CHECK (reusable IN (0,1)),
    _order bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    UNIQUE (id,owner_id,conversation_id),
    FOREIGN KEY (conversation_id,owner_id) REFERENCES conversations(id,owner_id),
    FOREIGN KEY (task_id,owner_id,conversation_id) REFERENCES tasks(id,owner_id,conversation_id)
);
CREATE INDEX ai_contexts_binding ON ai_contexts(owner_id,conversation_id,_order);
