-- Corrections are additive; original snapshots, cost inputs and signatures stay frozen.
CREATE TABLE procurement_reconciliations (
 id TEXT PRIMARY KEY, source_sha256 TEXT NOT NULL, source_name TEXT NOT NULL,
 actor TEXT NOT NULL, recorded_at TEXT NOT NULL, evidence TEXT NOT NULL,
 _order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE procurement_price_corrections (
 reconciliation_id TEXT NOT NULL REFERENCES procurement_reconciliations(id),
 batch_id TEXT NOT NULL, material_id TEXT NOT NULL, latest_price TEXT NOT NULL,
 price_date TEXT NOT NULL, sheet TEXT NOT NULL, cell TEXT NOT NULL, original_value TEXT,
 PRIMARY KEY(reconciliation_id,batch_id,material_id),
 FOREIGN KEY(batch_id,material_id) REFERENCES procurement_price_batch_items(batch_id,material_id),
 _order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 CHECK(latest_price::numeric>=0 AND latest_price::numeric<'Infinity'::numeric)
);
CREATE INDEX procurement_price_corrections_latest ON procurement_price_corrections(batch_id,material_id,_order DESC);
CREATE TABLE research_cost_corrections (
 reconciliation_id TEXT NOT NULL REFERENCES procurement_reconciliations(id),
 sequence BIGINT NOT NULL REFERENCES research_cost_records(sequence),
 signature TEXT NOT NULL, payload TEXT NOT NULL,
 summary_payload TEXT GENERATED ALWAYS AS ((payload::jsonb-ARRAY['graph','calculations','formula','source_hashes'])::text) STORED,
 current_payload TEXT GENERATED ALWAYS AS (research_current_payload(payload::jsonb)) STORED,
 PRIMARY KEY(reconciliation_id,sequence), _order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE INDEX research_cost_corrections_latest ON research_cost_corrections(sequence,_order DESC);
CREATE TABLE research_backfill_corrections (
 reconciliation_id TEXT NOT NULL REFERENCES procurement_reconciliations(id),
 purchase_version INTEGER NOT NULL, product_id TEXT NOT NULL,
 signature TEXT NOT NULL, payload TEXT NOT NULL,
 summary_payload TEXT GENERATED ALWAYS AS ((payload::jsonb-ARRAY['graph','calculations','formula','source_hashes','latest','inventory','lines'])::text) STORED,
 PRIMARY KEY(reconciliation_id,purchase_version,product_id),
 FOREIGN KEY(purchase_version,product_id) REFERENCES research_backfill_records(purchase_version,product_id),
 _order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE INDEX research_backfill_corrections_latest ON research_backfill_corrections(purchase_version,product_id,_order DESC);

CREATE VIEW procurement_effective_prices AS
 SELECT b.batch_id,b.material_id,b.code,b.name,b.unit,COALESCE(c.latest_price,b.latest_price) AS latest_price,
 b.inventory_price,b.in_transit_price,COALESCE(c.latest_price,b.recommended_price) AS recommended_price,b._order
 FROM procurement_price_batch_items b LEFT JOIN LATERAL (
 SELECT latest_price FROM procurement_price_corrections WHERE batch_id=b.batch_id AND material_id=b.material_id ORDER BY _order DESC LIMIT 1
 ) c ON true;
CREATE VIEW procurement_effective_sources AS
 SELECT b.batch_id,b.material_id,COALESCE(c.price_date,s.price_date) AS price_date,
 COALESCE(c.latest_price,s.raw_price) AS raw_price,
 CASE WHEN c.reconciliation_id IS NOT NULL THEN 'number' ELSE s.price_kind END AS price_kind,
 COALESCE(c.sheet,s.sheet) AS sheet,COALESCE(c.cell,s.cell) AS cell,
 COALESCE(r.source_sha256,s.sha256) AS sha256,s._order
 FROM procurement_price_batch_items b LEFT JOIN procurement_snapshot_sources s USING(batch_id,material_id)
 LEFT JOIN LATERAL (SELECT * FROM procurement_price_corrections WHERE batch_id=b.batch_id AND material_id=b.material_id ORDER BY _order DESC LIMIT 1) c ON true
 LEFT JOIN procurement_reconciliations r ON r.id=c.reconciliation_id
 WHERE s.material_id IS NOT NULL OR c.reconciliation_id IS NOT NULL;
CREATE VIEW research_effective_costs AS
 SELECT b.sequence,b.event_id,b.product_id,COALESCE(c.signature,b.signature) AS signature,
 COALESCE(c.payload,b.payload) AS payload,b._order,COALESCE(c.summary_payload,b.summary_payload) AS summary_payload,
 COALESCE(c.current_payload,b.current_payload) AS current_payload
 FROM research_cost_records b LEFT JOIN LATERAL (
 SELECT signature,payload,summary_payload,current_payload FROM research_cost_corrections WHERE sequence=b.sequence ORDER BY _order DESC LIMIT 1
 ) c ON true;
CREATE VIEW research_effective_backfill AS
 SELECT b.purchase_version,b.product_id,COALESCE(c.signature,b.signature) AS signature,
 COALESCE(c.payload,b.payload) AS payload,b._order,b.frozen_id,COALESCE(c.summary_payload,b.summary_payload) AS summary_payload
 FROM research_backfill_records b LEFT JOIN LATERAL (
 SELECT signature,payload,summary_payload FROM research_backfill_corrections WHERE purchase_version=b.purchase_version AND product_id=b.product_id ORDER BY _order DESC LIMIT 1
 ) c ON true;

