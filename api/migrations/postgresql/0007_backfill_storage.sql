-- Share immutable replay inputs; period results and their original signatures stay frozen.
CREATE TABLE research_backfill_frozen (
    id TEXT PRIMARY KEY,
    payload TEXT NOT NULL,
    _order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    CHECK (id = encode(sha256(convert_to(payload, 'UTF8')), 'hex'))
);
ALTER TABLE research_backfill_records ADD COLUMN frozen_id TEXT REFERENCES research_backfill_frozen(id);

CREATE FUNCTION research_freeze_backfill(value JSONB) RETURNS TEXT
LANGUAGE plpgsql SET search_path = public, pg_catalog AS $$
DECLARE
    frozen TEXT;
    fingerprint TEXT;
BEGIN
    SELECT jsonb_object_agg(key, item)::text INTO frozen
    FROM jsonb_each(value) AS fields(key, item)
    WHERE key = ANY(ARRAY['formula','graph','source_hashes']);
    IF frozen IS NULL THEN RETURN NULL; END IF;
    fingerprint := encode(sha256(convert_to(frozen, 'UTF8')), 'hex');
    INSERT INTO research_backfill_frozen(id, payload) VALUES(fingerprint, frozen)
    ON CONFLICT (id) DO NOTHING;
    IF NOT EXISTS (SELECT 1 FROM research_backfill_frozen WHERE id=fingerprint AND payload=frozen) THEN
        RAISE EXCEPTION 'Frozen content hash conflict';
    END IF;
    RETURN fingerprint;
END;
$$;

ALTER TABLE research_backfill_records DROP COLUMN summary_payload;
UPDATE research_backfill_records SET
    frozen_id=research_freeze_backfill(payload::jsonb),
    payload=(payload::jsonb - ARRAY['formula','graph','source_hashes'])::text;
ALTER TABLE research_backfill_records ADD COLUMN summary_payload TEXT GENERATED ALWAYS AS (
    (payload::jsonb - ARRAY['graph','calculations','formula','source_hashes','latest','inventory','lines'])::text
) STORED;
