CREATE FUNCTION procurement_price_modifier(material_key TEXT,target_version INTEGER) RETURNS JSONB
LANGUAGE sql STABLE SET search_path=public,pg_catalog AS $$
SELECT jsonb_build_object('kind',CASE WHEN kind='source' AND name='' THEN 'unknown' ELSE kind END,'name',name,'id',actor) FROM (
        SELECT b.version,3 AS priority,'system' AS kind,c.actor_name AS name,c.actor_id AS actor,c._order AS seq
        FROM procurement_saved_changes c JOIN procurement_updates u ON u.id=c.update_id
        JOIN procurement_price_batches b ON b.update_id=c.update_id
        WHERE c.material_id=material_key AND b.version<=target_version AND u.status!='cancelled'
        UNION ALL SELECT b.version,2,'source',COALESCE((SELECT string_agg(DISTINCT trim(ms.raw_json::jsonb->>0),'、' ORDER BY trim(ms.raw_json::jsonb->>0))
            FROM procurement_material_sources ms WHERE ms.material_id=s.material_id AND ms.sheet=s.sheet AND ms.sha256=s.sha256
            AND NULLIF(trim(ms.raw_json::jsonb->>0),'') IS NOT NULL),''),NULL,0
        FROM procurement_snapshot_sources s JOIN procurement_price_batches b ON b.id=s.batch_id
        WHERE s.material_id=material_key AND b.version<=target_version AND s.sha256 IS NOT NULL AND s.sha256!=''
        UNION ALL SELECT b.version,1,'unknown','',NULL,0 FROM procurement_price_history h
        JOIN procurement_imports imp ON imp.id=h.import_id JOIN procurement_price_batches b ON b.update_id=imp.update_id
        WHERE h.material_id=material_key AND b.version<=target_version
    ) attribution ORDER BY version DESC,priority DESC,seq DESC LIMIT 1;
$$;

CREATE TABLE procurement_price_read_points (
    batch_id TEXT NOT NULL,
    material_id TEXT NOT NULL,
    version INTEGER NOT NULL,
    published_at TEXT NOT NULL,
    price_date TEXT,
    batch_day TEXT NOT NULL,
    code TEXT NOT NULL,
    latest_price TEXT,
    source_id TEXT,
    source_date TEXT,
    price_kind TEXT,
    quote_date TEXT NOT NULL,
    quote_day TEXT NOT NULL,
    PRIMARY KEY(batch_id,material_id),
    FOREIGN KEY(batch_id,material_id) REFERENCES procurement_price_batch_items(batch_id,material_id) ON DELETE CASCADE,
    _order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE INDEX procurement_read_material_quote ON procurement_price_read_points(material_id,quote_day DESC,version DESC) WHERE latest_price IS NOT NULL AND (source_id IS NULL OR price_kind='number');
CREATE INDEX procurement_read_material_period ON procurement_price_read_points(material_id,batch_day,version);
CREATE INDEX procurement_read_period ON procurement_price_read_points(batch_day,material_id);

CREATE FUNCTION refresh_procurement_price_read(batch_key TEXT,material_key TEXT DEFAULT NULL) RETURNS void
LANGUAGE sql SET search_path=public,pg_catalog AS $$
    INSERT INTO procurement_price_read_points(batch_id,material_id,version,published_at,price_date,batch_day,code,latest_price,source_id,source_date,price_kind,quote_date,quote_day)
    SELECT b.id,i.material_id,b.version,b.published_at,b.price_date,LEFT(COALESCE(NULLIF(b.price_date,''),b.published_at),10),i.code,i.latest_price,s.material_id,s.price_date,s.price_kind,
        COALESCE(NULLIF(s.price_date,''),NULLIF(b.price_date,''),b.published_at),LEFT(COALESCE(NULLIF(s.price_date,''),NULLIF(b.price_date,''),b.published_at),10)
    FROM procurement_price_batches b JOIN procurement_price_batch_items i ON i.batch_id=b.id
    LEFT JOIN procurement_snapshot_sources s ON s.batch_id=i.batch_id AND s.material_id=i.material_id
    WHERE b.id=batch_key AND (material_key IS NULL OR i.material_id=material_key)
    ON CONFLICT(batch_id,material_id) DO UPDATE SET version=excluded.version,published_at=excluded.published_at,price_date=excluded.price_date,batch_day=excluded.batch_day,code=excluded.code,latest_price=excluded.latest_price,source_id=excluded.source_id,source_date=excluded.source_date,price_kind=excluded.price_kind,quote_date=excluded.quote_date,quote_day=excluded.quote_day;
$$;
SELECT refresh_procurement_price_read(id) FROM procurement_price_batches;
CREATE FUNCTION procurement_price_read_changed() RETURNS trigger
LANGUAGE plpgsql SET search_path=public,pg_catalog AS $$
BEGIN
    IF TG_TABLE_NAME='procurement_price_batches' THEN
        PERFORM refresh_procurement_price_read(NEW.id);
    ELSIF TG_OP='DELETE' THEN
        PERFORM refresh_procurement_price_read(OLD.batch_id,OLD.material_id);
    ELSE
        PERFORM refresh_procurement_price_read(NEW.batch_id,NEW.material_id);
    END IF;
    RETURN NULL;
END;
$$;
CREATE TRIGGER procurement_read_point AFTER INSERT OR UPDATE ON procurement_price_batch_items FOR EACH ROW EXECUTE FUNCTION procurement_price_read_changed();
CREATE TRIGGER procurement_read_point AFTER INSERT OR UPDATE OR DELETE ON procurement_snapshot_sources FOR EACH ROW EXECUTE FUNCTION procurement_price_read_changed();
CREATE TRIGGER procurement_read_point AFTER UPDATE ON procurement_price_batches FOR EACH ROW EXECUTE FUNCTION procurement_price_read_changed();
