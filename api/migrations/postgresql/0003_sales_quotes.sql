CREATE TABLE sales_batches (
 id TEXT PRIMARY KEY, owner_id TEXT NOT NULL REFERENCES identity_users(id),
 revision INTEGER NOT NULL CHECK(revision > 0), payload TEXT NOT NULL,
 created_at TEXT NOT NULL, updated_at TEXT NOT NULL, _order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE INDEX sales_batches_owner ON sales_batches(owner_id,updated_at);
CREATE TABLE sales_trials (
 id TEXT PRIMARY KEY, batch_id TEXT NOT NULL REFERENCES sales_batches(id),
 actor_id TEXT NOT NULL REFERENCES identity_users(id), created_at TEXT NOT NULL, payload TEXT NOT NULL,
 _order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE INDEX sales_trials_batch ON sales_trials(batch_id,created_at);
CREATE TABLE sales_records (
 id TEXT PRIMARY KEY, batch_id TEXT NOT NULL REFERENCES sales_batches(id), product_id TEXT NOT NULL,
 version INTEGER NOT NULL CHECK(version > 0), status TEXT NOT NULL CHECK(status IN ('active','superseded','void')),
 actor_id TEXT NOT NULL REFERENCES identity_users(id), created_at TEXT NOT NULL, payload TEXT NOT NULL,
 UNIQUE(batch_id,product_id,version), _order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE UNIQUE INDEX sales_record_current ON sales_records(batch_id,product_id) WHERE status='active';
CREATE TABLE sales_events (
 id TEXT PRIMARY KEY, batch_id TEXT NOT NULL REFERENCES sales_batches(id), actor_id TEXT NOT NULL REFERENCES identity_users(id),
 created_at TEXT NOT NULL, kind TEXT NOT NULL, payload TEXT NOT NULL, _order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
